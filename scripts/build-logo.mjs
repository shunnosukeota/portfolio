/**
 * ロゴ生成：埋め込み PNG（45KB）だった旧 logo.svg を、
 * ベクター化した S マーク + 既存の欧文パスのみで再構成し SVGO で最適化する。
 *
 *   npm run logo
 *
 * 出力:
 *   public/logo.svg             … 外部参照用（OG 等）
 *   public/logo-mark.svg        … S マーク単体
 *   src/components/ui/logoPaths.ts … インライン SVG 用のパスデータ（currentColor で描画）
 */
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { optimize } from 'svgo'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = await readFile(path.join(ROOT, 'assets/originals/logo.svg'), 'utf8')
const traced = await readFile(path.join(ROOT, 'assets/originals/s-mark-traced.svg'), 'utf8')

const letterPaths = [...src.matchAll(/<path d="([^"]+)" fill="black"\/>/g)].map((m) => m[1])
const sPath = traced.match(/ d="([^"]+)"/)[1]
if (letterPaths.length !== 7 || !sPath) throw new Error('unexpected source svg')

// 旧 SVG では S の PNG が 17×28.37 の矩形に y=-0.18 で配置されていた（468×781 → 0.03632 倍）
const S_TRANSFORM = 'translate(0 -0.18) scale(0.03632)'

const svgo = (svg) =>
  optimize(svg, {
    multipass: true,
    floatPrecision: 2,
    plugins: ['preset-default', { name: 'removeAttrs', params: { attrs: ['data-name'] } }],
  }).data

const wordmark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 119 28" width="119" height="28" fill="#0a0a0a">
<path d="${sPath}" transform="${S_TRANSFORM}"/>
${letterPaths.map((d) => `<path d="${d}"/>`).join('\n')}
</svg>`
const mark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 468 781" width="468" height="781" fill="#0a0a0a">
<path d="${sPath}"/>
</svg>`

const wordmarkOut = svgo(wordmark)
const markOut = svgo(mark)
await writeFile(path.join(ROOT, 'public/logo.svg'), wordmarkOut)
await writeFile(path.join(ROOT, 'public/logo-mark.svg'), markOut)

// インライン用パス（SVGO 後のパス d を抽出）
const optimizedPaths = [...wordmarkOut.matchAll(/<path d="([^"]+)"(?: transform="([^"]+)")?/g)].map((m) => ({
  d: m[1],
  transform: m[2],
}))
const ts = `// generated by scripts/build-logo.mjs — do not edit by hand
export const LOGO_VIEWBOX = '0 0 119 28'
export const LOGO_PATHS: { d: string; transform?: string }[] = ${JSON.stringify(optimizedPaths, null, 2)}
export const MARK_VIEWBOX = '0 0 468 781'
export const MARK_PATH = ${JSON.stringify(markOut.match(/<path d="([^"]+)"/)[1])}
`
await writeFile(path.join(ROOT, 'src/components/ui/logoPaths.ts'), ts)
console.log('logo.svg', wordmarkOut.length, 'bytes / logo-mark.svg', markOut.length, 'bytes')
