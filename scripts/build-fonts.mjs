/**
 * 和文フォント（Noto Sans JP）のサブセット生成
 *
 *   npm run fonts
 *
 * Google Fonts 経由（next/font/google）だと日本語は約120チャンク・合計 800KB 超になるため、
 * サイト内で実際に使用している文字 + かな・記号の基本セットだけを含む woff2 を生成し、
 * next/font/local で自前配信する（400 / 500 の2ウェイト。700 は未使用のため生成しない）。
 *
 * ⚠ コンテンツ（src/content 等）に新しい漢字を追加したら、このスクリプトを再実行してください。
 *   未収録の文字はシステムフォント（Hiragino Sans / Yu Gothic 等）で表示されます。
 *
 * 元フォント: assets/fonts/NotoSansJP-VF.ttf（Google Fonts の OFL 配布物。無ければ自動取得）
 */
import subsetFont from 'subset-font'
import { readFile, writeFile, readdir, stat, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SRC_FONT = path.join(ROOT, 'assets/fonts/NotoSansJP-VF.ttf')
const SRC_URL = 'https://github.com/google/fonts/raw/main/ofl/notosansjp/NotoSansJP%5Bwght%5D.ttf'
const OUT_DIR = path.join(ROOT, 'src/fonts')
// 使用ウェイトは 400（本文）/ 500（見出し）のみ。700 が必要になったら追加して `npm run fonts` → layout.tsx の src にも追記
const WEIGHTS = [400, 500]

/** サイト内テキストを収集する対象 */
const SCAN_DIRS = ['src/content', 'src/components', 'src/app', 'src/lib']

async function* walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) yield* walk(p)
    else if (/\.(tsx?|mjs|md)$/.test(e.name)) yield p
  }
}

function range(a, b) {
  let s = ''
  for (let c = a; c <= b; c++) s += String.fromCodePoint(c)
  return s
}

async function main() {
  try {
    await stat(SRC_FONT)
  } catch {
    console.log('downloading Noto Sans JP ...')
    const res = await fetch(SRC_URL)
    if (!res.ok) throw new Error(`download failed: ${res.status}`)
    await mkdir(path.dirname(SRC_FONT), { recursive: true })
    await writeFile(SRC_FONT, Buffer.from(await res.arrayBuffer()))
  }

  // 1. 使用文字の収集
  const chars = new Set()
  for (const dir of SCAN_DIRS) {
    for await (const f of walk(path.join(ROOT, dir))) {
      for (const ch of await readFile(f, 'utf8')) chars.add(ch)
    }
  }
  // 2. 基本セット：ASCII / Latin-1 / 一般句読点 / かな / CJK 記号 / 全角英数 / 矢印 / 記号類
  const base =
    range(0x20, 0x7e) + // ASCII
    '©®°±×÷' + // よく使う Latin-1 記号
    range(0x2010, 0x2027) + // ダッシュ・引用符・中黒など
    range(0x2030, 0x203a) +
    '←↑→↓⇒⇔' + // 矢印
    range(0x3000, 0x303f) + // CJK 記号・句読点
    range(0x3041, 0x309f) + // ひらがな
    range(0x30a0, 0x30ff) + // カタカナ
    '！？（）［］｛｝「」『』〈〉《》【】％＆＊＋，－．／：；＜＝＞＠＾＿｀｜～￥' + // 全角記号（英数字は半角に統一する前提）
    range(0x2460, 0x2469) + // 丸数字 ①〜⑩
    '■□▲△▼▽◆◇○●◎★☆…‥′″※〜〰〒〓〇々〆ー・'
  for (const ch of base) chars.add(ch)
  const text = [...chars].filter((c) => c.codePointAt(0) >= 0x20).join('')
  const kanji = [...chars].filter((c) => /\p{Script=Han}/u.test(c)).length
  console.log(`characters: ${chars.size} (kanji ${kanji})`)

  // 3. ウェイトごとに静的インスタンス化 + サブセット → woff2
  await mkdir(OUT_DIR, { recursive: true })
  const src = await readFile(SRC_FONT)
  for (const w of WEIGHTS) {
    const buf = await subsetFont(src, text, { targetFormat: 'woff2', variationAxes: { wght: w }, noLayoutClosure: true })
    const out = path.join(OUT_DIR, `NotoSansJP-${w}.subset.woff2`)
    await writeFile(out, buf)
    console.log(`  ${path.relative(ROOT, out)}  ${(buf.length / 1024).toFixed(1)}KB`)
  }
  await writeFile(
    path.join(OUT_DIR, 'charset.txt'),
    `# generated by scripts/build-fonts.mjs - ${chars.size} chars\n${text}\n`,
  )
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
